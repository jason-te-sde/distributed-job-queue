// TestServiceDescriptor pins the RPC surface of JobQueueService. Renaming,
// dropping or adding a method is a protocol change and must show up here.
func TestServiceDescriptor(t *testing.T) {
	svc := jobqueuev1.File_jobqueue_v1_jobqueue_proto.Services().ByName("JobQueueService")
	if svc == nil {
		t.Fatal("JobQueueService is missing from the file descriptor")
	}

	want := []string{
		"Enqueue", "Lease", "Heartbeat", "Ack", "Release", "GetJob",
		"CancelJob", "GetStats", "ListDeadJobs", "RequeueJob", "PurgeJobs",
	}
	var got []string
	for i := range svc.Methods().Len() {
		got = append(got, string(svc.Methods().Get(i).Name()))
	}
	if !slices.Equal(got, want) {
		t.Fatalf("JobQueueService methods = %v, want %v", got, want)
	}
}

// TestFieldNumbers pins the wire numbers of the fields that carry a lease's
// identity and an acknowledgement's outcome. A number cannot change once a
// client has been built against it, and a swap between two fields of the same
// type would still compile everywhere.
func TestFieldNumbers(t *testing.T) {
	tests := []struct {
		message string
		field   string
		number  protoreflect.FieldNumber
		oneof   string // expected oneof name, empty for a plain field
	}{
		{"LeaseRef", "id", 1, ""},
		{"LeaseRef", "queue", 2, ""},
		{"LeaseRef", "token", 3, ""},
		{"LeasedJob", "token", 5, ""},
		{"AckItem", "success", 2, "outcome"},
		{"AckItem", "failure", 3, "outcome"},
	}

	file := jobqueuev1.File_jobqueue_v1_jobqueue_proto
	for _, tc := range tests {
		t.Run(tc.message+"."+tc.field, func(t *testing.T) {
			msg := file.Messages().ByName(protoreflect.Name(tc.message))
			if msg == nil {
				t.Fatalf("message %s is missing", tc.message)
			}
			fd := msg.Fields().ByName(protoreflect.Name(tc.field))
			if fd == nil {
				t.Fatalf("field %s.%s is missing", tc.message, tc.field)
			}
			if fd.Number() != tc.number {
				t.Errorf("%s.%s has number %d, want %d", tc.message, tc.field, fd.Number(), tc.number)
			}
			var gotOneof string
			if oo := fd.ContainingOneof(); oo != nil {
				gotOneof = string(oo.Name())
			}
			if gotOneof != tc.oneof {
				t.Errorf("%s.%s is in oneof %q, want %q", tc.message, tc.field, gotOneof, tc.oneof)
			}
		})
	}
}

// TestEnumZeroValues pins the zero value of every enum. Proto3 decodes a
// missing field to zero, so each zero value must be the explicit
// "unspecified" one and not a real state.
func TestEnumZeroValues(t *testing.T) {
	want := map[protoreflect.Name]protoreflect.Name{
		"JobState":    "JOB_STATE_UNSPECIFIED",
		"LeaseStatus": "LEASE_STATUS_UNSPECIFIED",
		"AckStatus":   "ACK_STATUS_UNSPECIFIED",
	}

	enums := jobqueuev1.File_jobqueue_v1_jobqueue_proto.Enums()
	if enums.Len() != len(want) {
		t.Fatalf("the file declares %d enums, this test covers %d: add the new one to the table", enums.Len(), len(want))
	}
	for i := range enums.Len() {
		ed := enums.Get(i)
		wantZero, ok := want[ed.Name()]
		if !ok {
			t.Errorf("enum %s is not covered by this test", ed.Name())
			continue
		}
		zero := ed.Values().ByNumber(0)
		if zero == nil {
			t.Errorf("enum %s has no value 0", ed.Name())
			continue
		}
		if zero.Name() != wantZero {
			t.Errorf("enum %s has zero value %s, want %s", ed.Name(), zero.Name(), wantZero)
		}
	}
}

// TestFileOptionsAreGoOnly keeps the embedded descriptor free of options for
// other languages. buf managed mode would otherwise bake java_package, an
// Objective-C prefix, a C# namespace and similar into the generated bytes,
// which makes the committed output depend on options this repository never
// uses.
func TestFileOptionsAreGoOnly(t *testing.T) {
	opts, ok := jobqueuev1.File_jobqueue_v1_jobqueue_proto.Options().(*descriptorpb.FileOptions)
	if !ok || opts == nil {
		t.Fatal("the file descriptor carries no FileOptions, so go_package is missing")
	}
	if opts.GetGoPackage() == "" {
		t.Error("go_package is not set")
	}

	rest := proto.Clone(opts).(*descriptorpb.FileOptions)
	rest.GoPackage = nil
	rest.ProtoReflect().Range(func(fd protoreflect.FieldDescriptor, v protoreflect.Value) bool {
		t.Errorf("file option %s is set (%v); only go_package may be", fd.Name(), v)
		return true
	})
}
